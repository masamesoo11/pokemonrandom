#!/usr/bin/env node
/**
 * generate-sitemap-dates.mjs
 * -------------------------
 * Generates `src/lib/sitemap-dates.ts` from real git history so that the
 * sitemap <lastmod> reflects the last commit that actually changed each
 * section's content — instead of the deploy timestamp (which made Google
 * see every URL as "changed" on every deploy and eventually ignore lastmod).
 *
 * Runs automatically in CI before `next build` (see deploy.yml).
 * If git history is unavailable (e.g. shallow/fresh env), the committed
 * fallback file keeps the build green.
 */
import { execSync } from "node:child_process";
import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { resolve, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const target = resolve(root, "src/lib/sitemap-dates.ts");

/**
 * Section -> source paths that define that section's content.
 * A commit touching any listed path refreshes the section's lastmod.
 * Keep in sync with the page groups in src/app/sitemap.ts.
 */
const SECTIONS = {
  home: ["src/app/page.tsx", "src/components"],
  tools: [
    "src/app/random-pokemon",
    "src/app/pokemon-randomizer",
    "src/app/random-pokemon-picker",
    "src/app/universal-pokemon-randomizer",
    "src/app/random-team",
    "src/app/shiny-pokemon",
    "src/app/pokemon-quiz",
    "src/app/type-chart",
    "src/app/random-starter",
    "src/app/pokemon-of-the-day",
    "src/app/pokemon-compare",
    "src/app/type-wheel",
    "src/app/shiny-odds-calculator",
    "src/app/pokemon-search",
    "src/app/saved-teams",
    "src/app/tier-lists",
    "src/app/widgets",
    "src/app/embed",
    "src/app/api-docs",
    "src/components",
  ],
  pokedex: ["src/app/pokemon", "src/lib/pokemon-api.ts", "src/components"],
  generations: ["src/app/generation", "src/lib/pokemon-api.ts"],
  types: ["src/app/type", "src/lib/pokemon-api.ts", "src/lib/type-pokemon-map.json"],
  moves: ["src/app/moves", "src/lib/move-api.ts"],
  abilities: ["src/app/abilities", "src/lib/ability-api.ts"],
  blog: ["src/app/blog", "src/lib/blog-posts", "src/lib/blog-content-loader.ts"],
  info: [
    "src/app/about",
    "src/app/contact",
    "src/app/privacy",
    "src/app/terms",
    "src/app/cookies",
    "src/app/disclaimer",
    "src/app/dmca",
  ],
};

function lastCommitDate(paths) {
  try {
    const out = execSync(
      `git log -1 --format=%cI -- ${paths.map((p) => `"${p}"`).join(" ")}`,
      { cwd: root, encoding: "utf8", stdio: ["pipe", "pipe", "ignore"] }
    );
    return out.trim() || null;
  } catch {
    return null;
  }
}

const dates = {};
for (const [section, paths] of Object.entries(SECTIONS)) {
  const d = lastCommitDate(paths);
  if (d) dates[section] = d;
  else console.warn(`[sitemap-dates] WARNING: no git date for section "${section}"`);
}

if (Object.keys(dates).length === 0) {
  if (existsSync(target)) {
    console.log("[sitemap-dates] git unavailable — keeping committed fallback file.");
    process.exit(0);
  }
  dates.home = new Date().toISOString();
}

const body = `// AUTO-GENERATED by scripts/generate-sitemap-dates.mjs — DO NOT EDIT BY HAND.
// Regenerated on every deploy from git history (see .github/workflows/deploy.yml).
// Feeds the sitemap <lastmod>: deploys that do not change a section's content
// no longer refresh that section's lastmod (Google ignores gamed lastmod values).
export const SITEMAP_DATES: Record<string, string> = ${JSON.stringify(dates, null, 2)};
`;

let changed = true;
if (existsSync(target)) {
  changed = readFileSync(target, "utf8") !== body;
}
writeFileSync(target, body);
console.log(
  changed
    ? `[sitemap-dates] wrote ${Object.keys(dates).length} section dates to src/lib/sitemap-dates.ts`
    : "[sitemap-dates] unchanged — dates already current."
);
